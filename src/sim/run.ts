/**
 * Balance simulation.
 *
 *   node src/sim/run.ts            evaluate the shipped defaults and write reports/balance.md
 *   node src/sim/run.ts --grid     also search a grid of candidate settings (slower)
 *   node src/sim/run.ts --games 50 games per configuration (default 30)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadBank } from '../server/loadBank.ts';
import { DEFAULT_SETTINGS, type Settings } from '../shared/settings.ts';
import { MODEL } from './behavior.ts';
import { simulateGame, type GameReport } from './simulate.ts';

const args = process.argv.slice(2);
const flag = (name: string) => args.includes(`--${name}`);
const num = (name: string, fallback: number) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? Number(args[i + 1]) : fallback;
};
const GAMES = num('games', 30);
const TARGET_MIN = 8;
const TARGET_MAX = 12;

const bank = loadBank();
const min = (ms: number) => ms / 60000;
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / (xs.length || 1);
const f1 = (x: number) => x.toFixed(1);

interface Summary {
  settings: Settings;
  players: number;
  games: GameReport[];
  meanMin: number;
  minMin: number;
  maxMin: number;
  inTarget: number;
  rounds: number;
  finaleMin: number;
  pressure: number;
  saves: number;
  hearts: number;
}

function evaluate(settings: Settings, players: number, games = GAMES): Summary {
  const reports: GameReport[] = [];
  for (let seed = 1; seed <= games; seed++) reports.push(simulateGame({ players, seed, settings, bank }));
  const durations = reports.map((r) => min(r.durationMs));
  return {
    settings,
    players,
    games: reports,
    meanMin: mean(durations),
    minMin: Math.min(...durations),
    maxMin: Math.max(...durations),
    inTarget: durations.filter((d) => d >= TARGET_MIN && d <= TARGET_MAX).length / durations.length,
    rounds: mean(reports.map((r) => r.rounds)),
    finaleMin: mean(reports.map((r) => min(r.finaleMs))),
    pressure: mean(reports.map((r) => r.maxPressure)),
    saves: mean(reports.map((r) => r.saves)),
    hearts: mean(reports.map((r) => r.heartsEarned / r.players)),
  };
}

const out: string[] = [];
const w = (line = '') => out.push(line);

w('# Balance simulation report');
w();
w(`Generated by \`npm run sim${flag('grid') ? ' -- --grid' : ''}\` (${GAMES} simulated games per configuration).`);
w();
w('The simulation runs the real rules engine against simulated players on a virtual clock, using the');
w(`shipped category bank (${bank.categories.length} categories, ${bank.categories.reduce((a, c) => a + c.size, 0)} answers).`);
w(`Target: a 400-player game lasting ${TARGET_MIN}-${TARGET_MAX} minutes from start to winner.`);
w();
w('**Caveat.** The player model is an informed guess, not data. It decides the result as much as the');
w('settings do. Re-tune from real submission logs after the first events.');
w();
w('## Player model');
w();
w('| Knob | Value |');
w('| --- | --- |');
for (const [k, v] of Object.entries(MODEL)) w(`| ${k} | ${v} |`);
w();

if (flag('grid')) {
  const rows: Summary[] = [];
  for (const startHearts of [1, 2, 3]) {
    for (const fuseMs of [14000, 17000, 20000, 24000]) {
      for (const fuseDecay of [0.97, 0.985, 1]) {
        for (const rareThreshold of [0.7, 0.9]) {
          rows.push(evaluate({ ...DEFAULT_SETTINGS, startHearts, fuseMs, fuseDecay, rareThreshold }, 400, Math.min(GAMES, 10)));
        }
      }
    }
  }
  const score = (s: Summary) => Math.abs(s.meanMin - 10) + (1 - s.inTarget) * 4;
  rows.sort((a, b) => score(a) - score(b));
  w('## Grid search (400 players)');
  w();
  w('Sorted by closeness to a 10-minute mean with every game inside the target window. Other settings as shipped.');
  w();
  w('| startHearts | fuseMs | fuseDecay | rareThreshold | mean min | range | in target | rounds | finale min | hearts earned/player |');
  w('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const s of rows) {
    const x = s.settings;
    w(
      `| ${x.startHearts} | ${x.fuseMs} | ${x.fuseDecay} | ${x.rareThreshold} | ${f1(s.meanMin)} | ${f1(s.minMin)}-${f1(s.maxMin)} | ` +
        `${Math.round(s.inTarget * 100)}% | ${f1(s.rounds)} | ${f1(s.finaleMin)} | ${s.hearts.toFixed(2)} |`,
    );
  }
  w();
}

w('## Shipped defaults');
w();
w('```json');
w(JSON.stringify(DEFAULT_SETTINGS, null, 2));
w('```');
w();
w('| Players | mean min | range | in 8-12 min | main rounds | finale min | max pressure | wipeout saves | hearts earned/player |');
w('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
let at400: Summary | null = null;
for (const players of [2, 8, 25, 50, 100, 200, 300, 400, 500]) {
  const s = evaluate({ ...DEFAULT_SETTINGS, maxPlayers: 500 }, players);
  if (players === 400) at400 = s;
  w(
    `| ${players} | ${f1(s.meanMin)} | ${f1(s.minMin)}-${f1(s.maxMin)} | ${Math.round(s.inTarget * 100)}% | ${f1(s.rounds)} | ` +
      `${f1(s.finaleMin)} | ${f1(s.pressure)} | ${f1(s.saves)} | ${s.hearts.toFixed(2)} |`,
  );
}
w();

if (at400) {
  const g = at400.games[0];
  w(`## One 400-player game, round by round (seed ${g.seed})`);
  w();
  w(`Duration ${f1(min(g.durationMs))} min: ${f1(min(g.mainMs))} main + ${f1(min(g.finaleMs))} finale (${g.finalists} finalists, ${g.finaleTurns} turns).`);
  w();
  w('| Round | Category (answers) | Alive | Fuse s | Answered | Lost a heart | Eliminated | Submissions | Taken | Invalid | Rare claims |');
  w('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of g.trace) {
    w(
      `| ${r.round} | ${r.category} (${r.categorySize}) | ${r.aliveBefore} | ${f1(r.fuseMs / 1000)} | ${r.answered} | ` +
        `${r.lost}${r.saved ? ' (saved)' : ''} | ${r.out} | ${r.submissions} | ${r.taken} | ${r.invalid} | ${r.rare} |`,
    );
  }
  w();
  const pass =
    at400.meanMin >= TARGET_MIN && at400.meanMin <= TARGET_MAX
      ? `**Result: within target.** Mean ${f1(at400.meanMin)} min at 400 players; ${Math.round(at400.inTarget * 100)}% of simulated games land in the ${TARGET_MIN}-${TARGET_MAX} minute window.`
      : `**Result: outside target.** Mean ${f1(at400.meanMin)} min at 400 players.`;
  w(pass);
  w();
}

const dir = join(import.meta.dirname, '../../reports');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'balance.md'), out.join('\n'));
console.log(out.join('\n'));
